//! Internationalization (i18n): English is the source language; العربية (Arabic) is a full
//! runtime translation selected from the UI. The dictionary maps every English UI string
//! that appears in this app to its Arabic counterpart; unknown strings fall back to English.
//!
//! Usage: `crate::i18n::t("Save As…")` at display time. `tf("Slide {} of {}", &[..])`
//! translates patterns with `{}` placeholders. `set_language`/`language` drive the
//! language state (persisted in `UiState`). The shell keeps egui's left-to-right run
//! order until a bidi pass lands.

use std::sync::atomic::{AtomicU8, Ordering};

/// The UI language. English is the source language; العربية (Arabic) is right-to-left.
#[derive(Copy, Clone, Debug, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum Language {
    #[default]
    English,
    Arabic,
}

impl Language {
    /// BCP 47 code, e.g. `"en"`, `"ar"`.
    pub fn code(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::Arabic => "ar",
        }
    }

    /// The language's own name, shown in the language picker.
    pub fn name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::Arabic => "العربية",
        }
    }

    /// Parse a BCP 47 code (case-insensitive; unknown codes are English).
    pub fn from_code(code: &str) -> Self {
        if code.eq_ignore_ascii_case("ar") { Self::Arabic } else { Self::English }
    }

    /// Every language, in display order.
    pub const ALL: &'static [Language] = &[Language::English, Language::Arabic];
}

/// The active language, mirrored into a global so every `t()` call is cheap.
static LANGUAGE: AtomicU8 = AtomicU8::new(Language::English as u8);

/// Set the active language (called from the UI when it changes / on load).
pub fn set_language(l: Language) {
    LANGUAGE.store(l as u8, Ordering::Relaxed);
}

/// The active language.
pub fn language() -> Language {
    match LANGUAGE.load(Ordering::Relaxed) {
        1 => Language::Arabic,
        _ => Language::English,
    }
}

/// Is the UI in Arabic (right-to-left)?
pub fn is_arabic() -> bool {
    language() == Language::Arabic
}

/// Translate an English UI string into the active language. Unknown strings (and English)
/// come back unchanged, so untranslated additions keep working.
pub fn t(s: &str) -> String {
    if !is_arabic() {
        return s.to_string();
    }
    match tr_ar(s) {
        Some(ar) => ar.to_string(),
        None => s.to_string(),
    }
}

/// Translate a pattern with positional placeholders, substituting the arguments in order.
/// A placeholder is `{}` or a bare format spec such as `{:.1}` / `{:02}` (the argument is
/// expected to be pre-formatted); the translated pattern keeps its placeholders, so word
/// order is free.
pub fn tf(pattern: &str, args: &[String]) -> String {
    let mut out = t(pattern);
    for a in args {
        // The next positional placeholder: `{}`, or `{` `:` … `}` (a format spec, no nesting).
        let mut span = None;
        let b = out.as_bytes();
        let mut i = 0;
        while i < b.len() {
            if b[i] == b'{' {
                if let Some(e) = out[i + 1..].find('}') {
                    let inner = &out[i + 1..i + 1 + e];
                    if inner.is_empty() || inner.starts_with(':') {
                        span = Some(i..i + 2 + e);
                        break;
                    }
                }
            }
            i += 1;
        }
        if let Some(p) = span {
            out.replace_range(p, a);
        }
    }
    out
}

