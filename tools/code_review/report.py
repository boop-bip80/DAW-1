"""Render review results as console text, Markdown (for a PR) or JSON."""

from __future__ import annotations

import json
from typing import Any

from . import __version__
from .findings import SEVERITIES, SEVERITY_ICON, SEVERITY_RANK
from .pipeline import ReviewResult


def _location(file: str, line: int | None) -> str:
    return f"{file}:{line}" if line else file


def counts_text(result: ReviewResult) -> str:
    counts = [f"{result.count(name)} {name}" for name in SEVERITIES if result.count(name)]
    return ", ".join(counts) if counts else "none"


def render_console(result: ReviewResult, fail_on: str) -> str:
    base = f"{result.base_ref} ({result.base_rev[:10]})" if result.base_rev else result.base_ref
    mode = "" if result.mode == "branch" else f" · mode {result.mode}"
    reporter = "offline rules only" if result.offline else f"rules + {result.model}"
    lines = [
        f"Code review against {base}{mode}",
        f"{len(result.files)} file(s), +{result.added} −{result.removed} · "
        f"{len(result.findings)} finding(s): {counts_text(result)}",
        f"reviewer: {reporter}",
        "",
    ]
    if not result.findings:
        lines.append("No findings. ✅")
    for finding in result.findings:
        icon = SEVERITY_ICON.get(finding.severity, "•")
        badge = f" [{finding.verified}]" if finding.verified else ""
        lines.append(f"{icon} {finding.severity:<8} {_location(finding.file, finding.line)}  {finding.title}{badge}")
        for body_line in finding.body.splitlines():
            lines.append(f"    {body_line}")
        if finding.suggestion:
            lines.append("    suggestion:")
            lines.extend(f"      {line}" for line in finding.suggestion.splitlines())
        lines.append(f"    source: {finding.source} · confidence {finding.confidence:.2f}")
        lines.append("")
    if result.summaries:
        lines.append("Summary")
        for path, summary in result.summaries:
            lines.append(f"  {path}: {summary}")
        lines.append("")
    if fail_on != "none":
        failing = result.failing(fail_on)
        lines.append(f"Gate: {'FAIL' if failing else 'PASS'} (fail on {fail_on} or worse)")
    lines.append("Generated by `cargo xtask review`.")
    return "\n".join(lines)


def render_markdown(result: ReviewResult) -> str:
    base = f"`{result.base_ref}`" + (f" (`{result.base_rev[:10]}`)" if result.base_rev else "")
    reporter = "offline rules only" if result.offline else f"rules + `{result.model}`"
    out = [
        "# Code review",
        "",
        f"**Base:** {base} · **Mode:** {result.mode} · **Files:** {len(result.files)} "
        f"(+{result.added}/−{result.removed})",
        f"**Reviewer:** {reporter} · **Generated by:** `cargo xtask review` ({__version__})",
        "",
    ]
    if result.summaries:
        out.append("## Summary of the change")
        out.append("")
        for path, summary in result.summaries:
            out.append(f"- **`{path}`** — {summary}")
        out.append("")

    out.append(f"## Findings ({len(result.findings)})")
    out.append("")
    if not result.findings:
        out.append("No findings. ✅")
        out.append("")
    for finding in result.findings:
        icon = SEVERITY_ICON.get(finding.severity, "•")
        out.append(f"### {icon} {finding.severity} · {finding.category} · `{_location(finding.file, finding.line)}`")
        out.append("")
        out.append(f"**{finding.title}**")
        out.append("")
        out.append(finding.body)
        out.append("")
        if finding.suggestion:
            out.extend(
                [
                    "<details><summary>Suggested change</summary>",
                    "",
                    "```rust",
                    finding.suggestion,
                    "```",
                    "",
                    "</details>",
                    "",
                ]
            )
        meta = f"`source: {finding.source}` · confidence {finding.confidence:.2f}"
        if finding.verified:
            meta += f" · verified: {finding.verified}"
        out.append(meta)
        out.append("")

    if result.warnings:
        out.append("<details><summary>Reviewer notes</summary>")
        out.append("")
        for warning in result.warnings:
            out.append(f"- {warning}")
        out.append("")
        out.append("</details>")
        out.append("")
    return "\n".join(out)


def to_dict(result: ReviewResult) -> dict[str, Any]:
    return {
        "tool": "soundcraft-code-review",
        "version": __version__,
        "base": result.base_ref,
        "base_rev": result.base_rev,
        "mode": result.mode,
        "model": result.model,
        "offline": result.offline,
        "llm_used": result.llm_used,
        "stats": {
            "files": len(result.files),
            "added": result.added,
            "removed": result.removed,
            "findings": len(result.findings),
            **{name: result.count(name) for name in SEVERITY_RANK},
        },
        "summaries": [{"file": path, "summary": summary} for path, summary in result.summaries],
        "findings": [finding.to_dict() for finding in result.findings],
        "warnings": result.warnings,
    }


def render_json(result: ReviewResult) -> str:
    return json.dumps(to_dict(result), indent=2, ensure_ascii=False)
